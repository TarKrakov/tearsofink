package com.tarkrakov.tearsofink.entity.faction;

/**
 * Стороны Чернильных Земель. Кто с кем дружит или воюет — таблица в {@link Factions}.
 * PLAYER и MONSTER — не настоящие фракции, а «все игроки» и «все ванильные монстры».
 */
public enum Faction {
	/** Чернила: подчиняются Шпилю (бледные патрули, позже боссы и мобы Шпиля). */
	INK,
	/** Кровь: отщепенцы под сенью Багряных Вестников (жители, стража, Кровавые Охотники). */
	BLOOD,
	/** Рыболюди Озера: враждебны ко всем чужакам. */
	FISH,
	/** Игроки. */
	PLAYER,
	/** Ванильные монстры и боссы (зомби, скелеты, пауки, ...). */
	MONSTER,
	/** Охотники Шпиля и Кровавые: сами ни на кого не нападают, но на удар отвечают. */
	HUNTER,
	/** Чернильные охотники: безумны, воюют с патрулями, Кровью, Рыболюдьми и монстрами. */
	FERAL
}
